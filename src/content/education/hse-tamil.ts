export function getHseGroupTa(code: string): HseGroupTa | undefined {
  return HSE_GROUPS_TA.find((g) => g.code === code);
}

export function mergeGroupTa(code: string) {
  const en = HSE_GROUPS.find((g) => g.code === code);
  const ta = getHseGroupTa(code);
  if (!en || !ta) return undefined;
  return { en, ta };
}

