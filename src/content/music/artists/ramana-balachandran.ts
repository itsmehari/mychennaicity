const HALL_NOTE =
  "The sheet names the sabha and does not print a street or PIN. It prints a city only when the date is outside Chennai.";

function chennaiSabha(
  concert: Omit<MusicConcert, "city" | "holdHours" | "venueAddress" | "localityLabel">,
): MusicConcert {
  return {
    ...concert,
    holdHours: 3,
    venueAddress: `${concert.venueName}, Chennai`,
    localityLabel: "Chennai",
    city: "Chennai",
    note: concert.note ? `${concert.note} ${HALL_NOTE}` : HALL_NOTE,
  };
}

